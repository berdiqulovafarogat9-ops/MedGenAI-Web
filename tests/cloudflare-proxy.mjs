import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../deployment/cloudflare/_worker.js', import.meta.url), 'utf8');
const {default:worker} = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const env = {ASSETS:{fetch:async()=>new Response('asset')}};
assert.equal(await (await worker.fetch(new Request('https://example.org/'),env)).text(),'asset');
assert.equal((await worker.fetch(new Request('https://example.org/api/private'),env)).status,404);
let call;
globalThis.fetch = async (url,options)=> {call={url,options};return new Response('{"ok":true}',{status:201});};
const r = await worker.fetch(new Request('https://example.org/api/v1/test?x=1',{method:'POST',headers:{Authorization:'Bearer test',Cookie:'private=1',Origin:'https://example.org'},body:'{}'}),env);
assert.equal(call.url,'https://medgenai-web-1.onrender.com/api/v1/test?x=1');
assert.equal(call.options.headers.get('Authorization'),'Bearer test');
assert.equal(call.options.headers.get('Cookie'),null);
assert.equal(call.options.headers.get('Origin'),null);
assert.equal(call.options.method,'POST');
assert.equal(call.options.redirect,'manual');
assert.equal(r.status,201);
assert.equal(r.headers.get('Cache-Control'),'no-store');
globalThis.fetch = async()=>{throw new Error('offline');};
assert.equal((await worker.fetch(new Request('https://example.org/api/v1/health'),env)).status,502);
console.log('Cloudflare proxy: static routing, API boundary, forwarding, privacy headers and failure handling passed.');
